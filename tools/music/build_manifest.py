#!/usr/bin/env python3
"""Manifest bibliotek muzycznych (MUSIC_WAVES MW-1, MT-08).

Zbiera wpisy dla każdego gotowego pliku OGG:
  - z specyfikacji tools/music/specs/<id>.json (kind, bpm, takty, pętla, LUFS docelowe, album, stem),
  - z pomiaru pliku (długość w próbkach, LUFS, szczyt dBTP, wartości na krawędziach pętli),
    przy czym wynik finish.LAST_REPORT jest używany, gdy dotyczy tego samego pliku,
  - z assets/music/tracks.json dla plików spoza generatora (legacy: tytuł, licencja).

Pliki bez wyrenderowanego OGG nie trafiają do manifestu (raportowane jako "pending").

Użycie:
  python3 tools/music/build_manifest.py                      # zapis do assets/data/music.json
  python3 tools/music/build_manifest.py --root DIR --out F  # inny korzeń (testy)
  python3 tools/music/build_manifest.py --no-measure        # bez dekodowania (szybki podgląd)

Ścieżki w manifeście (`file`) są względne do assets/, np. "music/home/theme_cuy.ogg".
Wymaga ffmpeg (jak finish.py). Kod wyjścia: 0 OK, 1 błąd.
"""
import argparse
import glob
import json
import os
import re
import shutil
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import finish  # noqa: E402  (tylko odczyt: measure_file, OUT_DIR_BY_KIND, LAST_REPORT, SR_DEFAULT)

ROOT = finish.ROOT
SPECS_DIR = os.path.join(HERE, "specs")
SCHEMA = 1
OWN_LICENSE = "own, generated by code"
FOLDER_BY_KIND = dict(finish.OUT_DIR_BY_KIND, record="records")
ALBUM_RE = re.compile(r"_(a1|a2|b1|b2)$")
STEM_RE = re.compile(r"^(?P<group>.+)_(?P<stem>base|rhythm|lead|full)$")


def load_specs(specs_dir):
    specs = []
    for path in sorted(glob.glob(os.path.join(specs_dir, "*.json"))):
        name = os.path.basename(path)
        if name.startswith("_"):  # przykłady generatorów są pomijane
            continue
        with open(path, encoding="utf-8") as f:
            spec = json.load(f)
        spec["_path"] = path
        specs.append(spec)
    return specs


def rel_file(spec):
    folder = FOLDER_BY_KIND.get(spec["kind"], spec["kind"] + "s")
    return "music/%s/%s.ogg" % (folder, spec["id"])


def album_of(spec):
    if spec["kind"] != "record":
        return None
    return spec.get("album") or ALBUM_RE.sub("", spec["id"])


def stem_of(spec):
    """Grupa stemów: pole stem_of, albo prefiks nazwy przed _base/_rhythm/_lead/_full."""
    m = STEM_RE.match(spec["id"])
    if spec.get("stem_of"):
        return spec["stem_of"], m.group("stem") if m else None
    if m:
        return m.group("group"), m.group("stem")
    return None, None


def decode(path):
    """Dekodowanie OGG do (2, n) float64 przez ffmpeg (bez zapisu na dysk)."""
    exe = shutil.which("ffmpeg")
    if not exe:
        raise RuntimeError("ffmpeg nie jest zainstalowany")
    proc = subprocess.run([exe, "-hide_banner", "-nostdin", "-loglevel", "error", "-i", path,
                           "-f", "f32le", "-ac", "2", "-ar", str(finish.SR_DEFAULT), "pipe:1"],
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if proc.returncode != 0:
        raise RuntimeError("ffmpeg decode failed: %s" % proc.stderr[-200:].decode("utf-8", "replace"))
    data = np.frombuffer(proc.stdout, dtype="<f4").astype(np.float64)
    return data.reshape(-1, 2).T


def measure(abs_path):
    """Pomiar pliku: długość, LUFS, szczyt, wartości krawędzi. Zwraca dict."""
    samples = decode(abs_path)
    n = samples.shape[1]
    last = finish.LAST_REPORT
    if last and os.path.abspath(last.get("path", "")) == os.path.abspath(abs_path) \
            and last.get("lufs") is not None and last.get("true_peak_dbtp") is not None:
        lufs, peak = last["lufs"], last["true_peak_dbtp"]
        source = "finish.LAST_REPORT"
    else:
        lufs, peak = finish.measure_file(abs_path)
        source = "ebur128"
    return {
        "length_samples": int(n),
        "length_s": round(n / float(finish.SR_DEFAULT), 4),
        "lufs": round(float(lufs), 2),
        "peak_dbtp": round(float(peak), 2),
        "edge_first": round(float(np.max(np.abs(samples[:, 0]))) if n else 0.0, 5),
        "edge_last": round(float(np.max(np.abs(samples[:, -1]))) if n else 0.0, 5),
        "measured_by": source,
    }


def spec_item(spec, root, do_measure):
    rel = rel_file(spec)
    abs_path = os.path.join(root, "assets", rel)
    if not os.path.isfile(abs_path):
        return None
    loop = spec.get("loop", {})
    group, stem = stem_of(spec)
    item = {
        "id": spec["id"],
        "file": rel,
        "kind": spec["kind"],
        "title": spec["title"],
        "generated": True,
        "license": OWN_LICENSE,
        "bpm": spec["bpm"],
        "bars": spec["bars"],
        "meter": spec["meter"],
        "target_lufs": spec["master"]["lufs"],
        "loop": {
            "enabled": bool(loop.get("enabled", False)),
            "start_s": loop.get("start_s"),
            "end_s": loop.get("end_s"),
        },
        "album": album_of(spec),
        "stem_group": group,
        "stem": stem,
    }
    if do_measure:
        item.update(measure(abs_path))
    return item


def legacy_items(root, generated_files, do_measure):
    """Pliki OGG w assets/music spoza generatora; metadane z assets/music/tracks.json."""
    meta = {}
    tracks_path = os.path.join(root, "assets", "music", "tracks.json")
    if os.path.isfile(tracks_path):
        with open(tracks_path, encoding="utf-8") as f:
            for t in json.load(f):
                meta[t["file"]] = t
    items = []
    base = os.path.join(root, "assets")
    for abs_path in sorted(glob.glob(os.path.join(base, "music", "**", "*.ogg"), recursive=True)):
        rel = os.path.relpath(abs_path, base).replace(os.sep, "/")
        if rel in generated_files:
            continue
        t = meta.get(rel, {})
        item = {
            "id": t.get("id") or os.path.splitext(os.path.basename(rel))[0],
            "file": rel,
            "kind": "legacy",
            "title": t.get("title") or os.path.splitext(os.path.basename(rel))[0],
            "generated": False,
            "license": t.get("license") or None,
            "author": t.get("author"),
            "source_url": t.get("url"),
            "target_lufs": None,
            "loop": {"enabled": None, "start_s": None, "end_s": None},
        }
        if do_measure:
            item.update(measure(abs_path))
        items.append(item)
    return items


def build(root, specs_dir, do_measure):
    specs = load_specs(specs_dir)
    items, pending = [], []
    for spec in specs:
        item = spec_item(spec, root, do_measure)
        if item is None:
            pending.append(spec["id"])
        else:
            items.append(item)
    generated_files = {i["file"] for i in items}
    items += legacy_items(root, generated_files, do_measure)
    items.sort(key=lambda i: (not i["generated"], i["id"]))

    albums = {}
    for i in items:
        if i.get("album"):
            albums[i["album"]] = albums.get(i["album"], 0) + 1
    records = [{"id": a, "tracks": n} for a, n in sorted(albums.items())]

    return {
        "schema": SCHEMA,
        "generated_by": "tools/music/build_manifest.py",
        "sample_rate": finish.SR_DEFAULT,
        "counts": {
            "total": len(items),
            "generated": sum(1 for i in items if i["generated"]),
            "legacy": sum(1 for i in items if not i["generated"]),
            "records": len(records),
            "specs": len(specs),
            "pending": len(pending),
        },
        "records": records,
        "items": items,
    }, pending


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=ROOT, help="korzeń repozytorium (domyślnie repo)")
    ap.add_argument("--specs", default=SPECS_DIR, help="katalog specyfikacji")
    ap.add_argument("--out", default=None, help="plik wyjściowy (domyślnie <root>/assets/data/music.json)")
    ap.add_argument("--no-measure", action="store_true", help="pomiń dekodowanie i LUFS")
    args = ap.parse_args()

    root = os.path.abspath(args.root)
    out = args.out or os.path.join(root, "assets", "data", "music.json")
    try:
        manifest, pending = build(root, args.specs, not args.no_measure)
    except (RuntimeError, OSError, KeyError, json.JSONDecodeError) as e:
        print("build_manifest: %s" % e, file=sys.stderr)
        return 1

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)
        f.write("\n")

    c = manifest["counts"]
    print("manifest: %s" % out)
    print("items: %d (generated %d, legacy %d), records: %d, specs: %d, pending: %d"
          % (c["total"], c["generated"], c["legacy"], c["records"], c["specs"], c["pending"]))
    if pending:
        print("pending (brak OGG): " + ", ".join(pending))
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Writes assets/sprites/palettes.json: exact colour remaps (from the ginger sheet) for every coat.
Usage: python palettes.py [out_json]"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pig

# palette id (game) -> coat key in pig.COATS
PALETTES = {
    'tricolor': 'tricolor',
    'dutch': 'dutch',
    'agouti': 'agouti',
    'albino': 'albino',
    'cinnamon': 'cinnamon',
    'black_white': 'czarno-biala',   # companion look, not offered at adoption
    'cream': 'kremowa',              # companion look, not offered at adoption
}
DEFAULT = 'tricolor'


def hexs(c):
    return '#%02x%02x%02x' % tuple(int(v) for v in c[:3])


def build():
    out = {'note': 'Exact colour remap of the ginger sheets. Each entry is [fromHex, toHex]. Generated by tools/art/palettes.py',
           'default': DEFAULT, 'palettes': {}}
    for pid, coat in PALETTES.items():
        pairs = []
        c = pig.COATS[coat]
        for ramp in ('orange', 'rust'):
            for a, b in zip(pig.RAMP[ramp], c.get(ramp, pig.RAMP[ramp])):
                if hexs(a) != hexs(b):
                    pairs.append([hexs(a), hexs(b)])
        if 'eye' in c:
            pairs.append([hexs(pig.EYE), hexs(c['eye'])])
        out['palettes'][pid] = pairs
    return out


if __name__ == '__main__':
    dst = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', '..', 'assets', 'sprites', 'palettes.json')
    json.dump(build(), open(dst, 'w'), indent=1)
    print('wrote', dst)

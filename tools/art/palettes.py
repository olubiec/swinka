"""Writes assets/sprites/palettes.json (v2): zone-coded master colours, patterns (zone -> slot), palettes (slot -> 4 shades),
senior (faded) palettes, legacy ids and the named collection.
A coat = exact colour remap: for every zone/shade (and speckle 'tick') pixel of the master sheet, master colour -> palette[slot][shade].
Usage: python palettes.py [out_json]"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import patterns as PT


def hexs(c):
    return '#%02x%02x%02x' % tuple(int(v) for v in c[:3])


def build():
    PT.check_master_unique()
    master = {}
    for z in PT.ZONES:
        master[z] = {'shade': [hexs(PT.master_colour(z, lv)) for lv in range(4)],
                     'tick': [hexs(PT.master_colour(z, lv, True)) for lv in range(3)]}
    pals, senior = {}, {}
    for pid, p in PT.PALETTES.items():
        pals[pid] = {s: [hexs(c) for c in p[s]] for s in 'ABWK'}
        senior[pid] = {s: [hexs(c) for c in PT.fade_ramp(p[s])] for s in 'ABWK'}
        if 'eye' in p:
            pals[pid]['eye'] = hexs(p['eye'])
            senior[pid]['eye'] = hexs(p['eye'])
    v2 = {'version': 2,
            'note': 'Zone-coded master sheets + exact colour remap. Generated by tools/art/palettes.py. '
                    'Remap: master[zone].shade[i] -> palettes[id][patterns[pat][zone]][i]; master[zone].tick[i] -> the same colour, '
                    'or when patterns[pat].tick is \'light\' that colour lightened by 42 %; eye colour #2b1712 -> palettes[id].eye if present. '
                    'Senior sheets use senior_palettes (light fade). Everything else in the sheet is coat independent.',
            'default': {'pattern': PT.DEFAULT_PATTERN, 'palette': PT.DEFAULT_PALETTE},
            'eye': '#2b1712', 'zones': PT.ZONES, 'master': master, 'patterns': PT.PATTERNS,
            'palettes': pals, 'senior_palettes': senior,
            'legacy': {k: {'pattern': v[0], 'palette': v[1]} for k, v in PT.LEGACY.items()},
            'named': {k: dict(zip(('breed', 'build', 'pattern', 'palette'), v)) for k, v in PT.NAMED.items()}}
    return v2


def pairs(pattern, palette, senior=False):
    """List of [from, to] hex pairs (as the game composes them from the v2 model): master zone/shade/tick colour -> coat colour."""
    out = []
    for z in PT.ZONES:
        sh, tk = PT.zone_ramp(pattern, palette, z, senior), PT.zone_ramp(pattern, palette, z, senior, True)
        for i in range(4):
            out.append([hexs(PT.master_colour(z, i)), hexs(sh[i])])
        for i in range(3):
            out.append([hexs(PT.master_colour(z, i, True)), hexs(tk[i])])
    e = PT.PALETTES[palette].get('eye')
    if e is not None:
        out.append(['#2b1712', hexs(e)])
    return [p for p in out if p[0] != p[1]]   # identity pairs change nothing


def build_file():
    """palettes.json: v1-compatible `palettes` (id -> [from,to] pairs, read as is by the existing JS/C# loaders) plus the 'v2' model.
    Ids: legacy game ids, '<pattern>.<palette>' for every combination, and '<id>@senior' (faded coat) for legacy ids and the named pigs."""
    v2 = build()
    out = {'note': 'Exact colour remap of the zone-coded master sheets. Each entry is [fromHex, toHex]. Generated by tools/art/palettes.py. '
                   'Ids: legacy ids, <pattern>.<palette> and <id>@senior for the senior (faded) sheets; model details under v2.',
           'default': 'tricolor', 'palettes': {}, 'v2': v2}
    P = out['palettes']
    for lid, (pt, pl) in PT.LEGACY.items():
        P[lid] = pairs(pt, pl)
        P[lid + '@senior'] = pairs(pt, pl, True)
    for pt in PT.PATTERNS:
        for pl in PT.PALETTES:
            P[pt + '.' + pl] = pairs(pt, pl)
    for (_, _, pt, pl) in PT.NAMED.values():
        P[pt + '.' + pl + '@senior'] = pairs(pt, pl, True)
    return out


if __name__ == '__main__':
    dst = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', '..', 'assets', 'sprites', 'palettes.json')
    json.dump(build_file(), open(dst, 'w'), separators=(',', ':'))
    print('wrote', dst)
